import { test, expect, login, portfolioId, riskId } from './fixtures'

for (const mobile of [false, true]) {
  test(`risk tabs and readable report ${mobile ? 'mobile' : 'desktop'}`, async ({ page, api }, testInfo) => {
    api.hasPortfolio = api.hasHolding = true
    if (mobile) await page.setViewportSize({ width: 390, height: 844 })
    await login(page)
    await page.goto(`/risk-runs/${portfolioId}`)
    await expect(page.getByRole('tab', { name: '風險總覽', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(page.locator('.overview-metrics')).toContainText('歷史最大回撤')
    await expect(page.locator('.overview-metrics')).toContainText('95% 單日損失門檻')
    await expect(page.locator('table[aria-label="主要風險來源"] th')).toHaveCount(4)
    expect(api.requests.filter(r => r.path === `/portfolios/${portfolioId}/risk`)).toHaveLength(0)
    await page.screenshot({ path: testInfo.outputPath('overview.png'), fullPage: true })
    await page.getByRole('tab', { name: '回測與方法', exact: true }).click()
    await expect(page.getByRole('button', { name: '執行歷史回測', exact: true })).toBeVisible()
    expect(api.requests.filter(r => r.method === 'POST' && /quality-validation|calculations|backtests/.test(r.path))).toHaveLength(0)
    expect(api.requests.filter(r => r.path === `/portfolios/${portfolioId}/risk`)).toHaveLength(0)
    await page.getByText('計算口徑與技術明細', { exact: true }).click()
    await expect(page.getByText('ALGORITHM VERSION', { exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('methods.png'), fullPage: true })
    await page.getByRole('tab', { name: '風險總覽', exact: true }).click()
    await expect(page.getByText('ALGORITHM VERSION', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '儲存風險報告', exact: true }).click()
    const report = page.getByRole('article', { name: '已保存的風險報告' })
    await expect(report).toBeVisible()
    await expect(report.locator('pre')).toHaveCount(0)
    await expect(report).toContainText('尚未回測')
    expect(api.requests.filter(r => r.method === 'POST' && r.path.endsWith(`/from-calculation/${riskId}`))).toHaveLength(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath('report.png'), fullPage: true })
    await page.emulateMedia({ media: 'print' })
    await expect(report).toBeVisible()
    await expect(page.locator('.kimi-app-header')).not.toBeVisible()
    await expect(report.getByRole('heading', { name: '風險報告快照', exact: true })).toHaveCSS('color', 'rgb(17, 17, 17)')
    await expect(page.getByRole('tab', { name: '風險總覽', exact: true })).not.toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('print.png'), fullPage: true })
  })
}
