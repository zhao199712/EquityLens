"""E2: correctly specified DGP passed through the production replay.
Two assets, GARCH(1,1) marginals with iid joint standardized multivariate-t(6)
innovation vectors (corr 0.5) -- exactly the structure VT-GARCH-t + joint-vector FHS
assumes. Forecasts come from collect_forecasts_multi (production fit cadence,
filtering, nearest-rank, 10,000 draws); realised returns are generated by the DGP,
independently of the forecasts. Parameters are estimated, as in production."""
import json, sys
import numpy as np
from multiprocessing import Pool
from common import evaluate
from equitylens_mathematics.research.es_backtest import collect_forecasts_multi

import os
OOS = int(os.environ.get("OOS", "1500"))
_unused, BANK, BURN, REPS, NU = 0, 252, 500, 1000, 6.0
PARAMS = [(1.8**2, 0.07, 0.91), (2.2**2, 0.10, 0.86)]  # percent-unit unconditional var, alpha, beta

def simulate(rng, length):
    g = rng.multivariate_normal([0, 0], [[1, .5], [.5, 1]], size=length)
    w = rng.chisquare(NU, size=length) / NU
    e = g / np.sqrt(w)[:, None] * np.sqrt((NU - 2) / NU)
    r = np.empty((2, length))
    for a, (v, al, be) in enumerate(PARAMS):
        om = v * (1 - al - be); s2 = v
        for t in range(length):
            r[a, t] = np.sqrt(s2) * e[t, a]
            s2 = om + al * r[a, t] ** 2 + be * s2
    return r[:, BURN:] / 100.0

def one(seed):
    rng = np.random.default_rng(20_000 + seed)
    r = simulate(rng, BURN + BANK + OOS)
    dates = [str(i) for i in range(r.shape[1])]
    fcs = collect_forecasts_multi(r, {"conc": (np.array([.76, .24]), f"e2:c:{seed}"),
                                      "equal": (np.array([.5, .5]), f"e2:e:{seed}")},
                                  dates, BANK, 10_000, keep_previous_on_fit_failure=True)
    return {k: dict(evaluate(fc, REPS, f"e2:{k}:{seed}"), fails=len(fc.fit_failures)) for k, fc in fcs.items()}

if __name__ == "__main__":
    n = int(sys.argv[1]); out = sys.argv[2]
    with Pool(4) as pool:
        res = pool.map(one, range(n))
    json.dump(res, open(out, "w"))
